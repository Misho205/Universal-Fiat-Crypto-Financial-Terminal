"""Meta Muse Spark AI services — ADVISORY ONLY, never execution authority.

Security rules (enforced here, in meta_client.py, and in api.py):
- AI output cannot authorize, capture, refund, sign, release, or move funds.
  Deterministic backend rules (contracts.validate_terms, policy decisions,
  provider adapters) alone enforce payment authorization and execution.
- API key comes from Modal Secret / env (MODEL_API_KEY), never from the
  frontend, never logged, never returned in responses.
- Cardholder data, private keys/seeds, and unnecessary PII are scrubbed
  before any request (meta_client.scrub_payload).
- Every AI result is validated against an explicit schema; failures degrade
  to a safe fallback flagged validated=False (fraud fallback fails CLOSED
  to "high" risk = human review required).
"""
from __future__ import annotations

from typing import Any

from . import config, meta_client
from .logging_util import get_logger, log_event
from .meta_client import (
    ContractAnalysis,
    FraudSignals,
    MetaClientError,
    RoutingRecommendation,
    TransactionExplanation,
    validated,
)

logger = get_logger("hybridpay.ai")

_ADVISORY_NOTICE = "AI output is advisory only; validator + human acceptance required."
_JSON_ONLY = " Reply with a single JSON object matching exactly these fields. No markdown, no extra text."


def _envelope(kind: str, data: dict[str, Any], *, validated_ok: bool, model: str) -> dict[str, Any]:
    return {"kind": kind, "data": data, "validated": validated_ok, "model": model,
            "advisoryOnly": True, "notice": _ADVISORY_NOTICE}


def draft_agreement_brief(order: dict[str, str]) -> dict[str, str]:
    """Legacy draft helper (kept for /api/ai/analyze). Offline-safe stub without key."""
    if not meta_client.has_key():
        log_event(logger, "ai.stub", reason="MODEL_API_KEY missing")
        return {
            "suggestion": "Fixed-price EUR agreement, pay-after-condition, single beneficiary.",
            "model": "stub (no key)",
        }
    log_event(logger, "ai.draft", model=config.META_MODEL_ID)
    return {
        "suggestion": "Draft generated by Meta model (must pass validator + human acceptance).",
        "model": config.META_MODEL_ID,
    }


def explain_transaction(tx: dict[str, Any], tenant: str) -> dict[str, Any]:
    meta_client.check_rate_limit(tenant)  # may raise RATE_LIMITED (mapped to 429)
    if not meta_client.has_key():
        stub = validated(TransactionExplanation, {
            "summary": "Sandbox payment: review amount, asset, fees, and agreement terms on the receipt.",
            "amountMinor": str(tx.get("amountMinor", "")), "asset": str(tx.get("asset", "")),
            "feeNotes": "Fees per agreement terms; sandbox amounts are not real funds.",
            "warnings": ["AI unavailable (no key); this is a static explanation."]})
        return _envelope("explanation", stub.model_dump(), validated_ok=True, model="stub (no key)")
    try:
        parsed, meta = meta_client.call_model(
            "You explain sandbox payment transactions in plain language for merchants." + _JSON_ONLY,
            {"task": "explain", "transaction": tx}, tenant)
        data = validated(TransactionExplanation, parsed)
        return _envelope("explanation", data.model_dump(), validated_ok=True, model=meta["model"])
    except MetaClientError as exc:
        log_event(logger, "ai.fallback", task="explain", code=exc.code)
        fallback = validated(TransactionExplanation, {
            "summary": "AI explanation unavailable; refer to the receipt and agreement terms.",
            "warnings": ["AI_UNAVAILABLE"]})
        return _envelope("explanation", fallback.model_dump(), validated_ok=False, model=config.META_MODEL_ID)


def fraud_signals(tx: dict[str, Any], tenant: str) -> dict[str, Any]:
    """Fail CLOSED: any AI failure yields riskLevel high (human review required)."""
    meta_client.check_rate_limit(tenant)  # may raise RATE_LIMITED (mapped to 429)
    if not meta_client.has_key():
        stub = validated(FraudSignals, {"riskLevel": "high", "scoreBps": 10000, "indicators": [
            {"code": "AI_UNAVAILABLE", "detail": "No model key; manual review required.", "weightBps": 10000}]})
        return _envelope("fraud", stub.model_dump(), validated_ok=True, model="stub (no key)")
    try:
        parsed, meta = meta_client.call_model(
            "You are a fraud-risk assistant. List risk indicators with weights; never approve or block payments."
            + _JSON_ONLY,
            {"task": "fraud", "transaction": tx}, tenant)
        data = validated(FraudSignals, parsed)
        return _envelope("fraud", data.model_dump(), validated_ok=True, model=meta["model"])
    except MetaClientError as exc:
        log_event(logger, "ai.fallback", task="fraud", code=exc.code)
        fallback = validated(FraudSignals, {"riskLevel": "high", "scoreBps": 10000, "indicators": [
            {"code": "AI_UNAVAILABLE", "detail": "Model error; manual review required.", "weightBps": 10000}]})
        return _envelope("fraud", fallback.model_dump(), validated_ok=False, model=config.META_MODEL_ID)


